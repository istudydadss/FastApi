# ===== 我的第一个 FastAPI 程序 =====
#
# 写代码前,先在脑子里用"人话"想清楚三步(这就是代码思想):
#   第 1 步:我要开一家"网络餐厅"来接待请求   -> 创建一个 FastAPI 实例
#   第 2 步:客人访问哪个网址,我要做什么      -> 定义一个函数,并绑定到网址
#   第 3 步:做完要把什么"端"给客人           -> return 返回结果
#
# 下面每一行代码,都对应上面的一句"人话"。


# 【翻译第 1 步的前半句】先把 FastAPI 这个"工具箱"拿进来
# 人话:我要开餐厅,得先去把开店用的家伙事儿搬进来
from fastapi import FastAPI


# 【翻译第 1 步的后半句】开一家餐厅
# 人话:app 就是这家店的"总管",以后所有接口(菜)都挂在它身上
app = FastAPI()
#bnm,/


# 【翻译第 2 步】告诉总管:当有人访问根网址 "/" 时,执行下面这个函数
# 人话:@app.get("/") 就是"菜单上的一道菜",客人点了 "/" 就上这道菜
# 小技巧:@ 开头的这一行叫"装饰器",你可以理解成"给函数贴一个网址标签"
@app.get("/")
def read_root():
    # 【翻译第 3 步】把结果"端"给客人
    # 人话:return 一个字典,FastAPI 会自动把它变成 JSON 格式发给浏览器
    return {"message": "你好,这是我写的第一个 API!"}
@app.get("/wangziming")
def read_wangziming():
    return {"message": "你好,我叫王梓铭!"}


# ============================================================
# 【新知识点:路径参数】用一个函数搞定所有名字
# ============================================================
# 还是先想"人话三步":
#   第 1 步:餐厅已经开好了(app 还在),不用重开
#   第 2 步:客人访问 "/hello/任意名字",我要接住那个名字
#   第 3 步:把名字拼进问候语,还给客人
#
# 核心难点:名字是不确定的(张三、李四、王五...),怎么接住?
# 答案:在网址里挖一个"洞" {name},谁来都能掉进这个洞被接住


# 【翻译第 2 步】注意网址里的 {name},它是一个"占位符",也就是一个"洞"
# 人话:/hello/ 后面跟什么都行,跟的那个东西会被塞进 name 这个洞里
@app.get("/hello/{name}")
# 【最关键的一行】函数参数 name,必须和上面网址里的 {name} 一字不差
# 人话:name: str 里的 ": str" 就是类型注解,告诉 FastAPI"这个洞接的是文字"
def read_hello(name: str):
    # 【翻译第 3 步】f"..." 叫格式化字符串,里面的 {name} 会被换成真实的名字
    # 人话:客人访问 /hello/张三,这里的 {name} 就变成"张三"
    return {"message": f"你好,{name}!欢迎学习 FastAPI!"}


# ============================================================
# 【类型注解的威力】只改一个词,FastAPI 就自动帮你校验数据
# ============================================================
# 上面的 name 是 str(文字),来者不拒,是啥都行。
# 下面这个 age,我故意写成 int(整数),让你看看类型注解有多聪明:
#   - 访问 /age/18   -> 正常,因为 18 是整数
#   - 访问 /age/abc  -> 直接报错 422!因为 abc 不是整数,FastAPI 帮你拦下了
# 这就是你之前学的类型注解在真实框架里的作用:
#   不用你自己写 if 判断,它自动校验 + 自动把 "18" 转成数字 18


@app.get("/age/{age}")
# 人话:age: int 告诉 FastAPI"这个洞只接整数",接到别的东西就自动报错
def read_age(age: int):
    # 注意 age + 1:因为 age 被声明成 int,FastAPI 已自动把它变成数字,
    # 所以能直接做数学运算。如果类型注解写成 str,这里就会报错(文字不能 +1)
    return {"message": f"你今年 {age} 岁了", "明年": age + 1}




@app.get("/wangziming/{n}")
def sum(n: int):
    sum = 0
    for i in range(n):
        sum += i
    return {"sum": sum}

